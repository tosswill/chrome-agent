#!/usr/bin/env python3
"""Polite, read-only Instagram research in a shared, signed-in chrome-agent browser (instagram).

Generated by add-research-site/scripts/onboard_site.py scaffold; fill in the readers for the pages
this site's research needs (search results, product pages, reviews, Q&A) and keep them read-only.

CLI (each command prints JSON):

    instagram_tab.py open [--wait [SECONDS]]      claim a window -> {"target": ID} (`stop` when signed out)
    instagram_tab.py search ID QUERY              the sidebar Search panel, typed like a person; returns the
                       suggested profiles, tags and places (no page load; counts as one against the caps)
    instagram_tab.py profile ID [HANDLE]          a public profile (no HANDLE: the profile already open, no load): name, followers, following, posts, bio,
                       category, and the post and reel links visible on the grid (1 load)
    instagram_tab.py post ID [URL|CODE]           one post or reel (no ref: the post already open, no load): author, date, likes and comments as shown,
                       caption, image description, comments visible without expanding (1 load)
    instagram_tab.py nav ID URL                   paced page load on instagram.com
    instagram_tab.py read ID [--selector CSS] [--from N] [--length N]   the page as text (headings, [text](links),
                       [button: labels]); read on with --from next_from (no load)
    instagram_tab.py links ID [--grep T] [--max N]       visible links, with on_site (no load)
    instagram_tab.py click ID --text T | --selector CSS | --href URL [--nth N]   click like a person; refuses
                       votes, follows, comments, posts, saves, purchases, sign-out, form fields and off-site links
    instagram_tab.py scroll ID [--screens N]             mouse-wheel scroll (negative: up)
    instagram_tab.py back ID                             previous page in this window
    instagram_tab.py shot ID [--out PATH] [--photo | --grid N | --selector CSS]   screenshot of the window, or one
                       element with no side bars: --photo the largest image in view (a post's photo),
                       --grid N the N-th grid thumbnail in view, --selector any element
    instagram_tab.py eval ID JS   read something off the page (disabled unless RESEARCH_ALLOW_EVAL=1)
    instagram_tab.py close ID | list | gc         release window / show / clean up claims

Environment (INSTAGRAM_TAB_*): INSTANCE (instagram), MAX (1 window), GAP (25 s between loads),
MAX_LOADS (15 per window), DAY_CAP (30 loads per rolling 24 h, all windows), STATE (/tmp/chrome-agent-instagram).
The account is new (2026-11-25): the low caps keep its first days gentle. Raise DAY_CAP only on the user's word.
"""
import json
import random
import sys
import time
from pathlib import Path
import os
import re


HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "lib"))
from research_core import BLOCK_CHECK_JS, Fail, Site, common_cli, opt, run_cli  # noqa: E402

# Signed-in checks from onboarding step 6 (scaffold --account-selector / --session-cookie fill these in).
ACCOUNT_SELECTOR = 'a[href*="/direct/inbox"]'  # an element only a signed-in page shows (the account menu), or None
SESSION_COOKIE = 'sessionid'      # the site's signed-in cookie (httpOnly is fine), or None

# Where the tab is, whether the site shows the signed-in account, and whether a wall is up.
PAGE_STATE_JS = r"""(() => {
  const acct = """ + json.dumps(ACCOUNT_SELECTOR) + r""";
  const header = (document.querySelector("header")?.innerText || "").toLowerCase();
  const loggedIn = (acct && document.querySelector(acct)) ? true : (/\bsign in\b|\blog in\b/.test(header) ? false : null);
  return Object.assign({url: location.href, title: document.title, loggedIn}, """ + BLOCK_CHECK_JS + r""");
})()"""


def _cookie_session(site: Site) -> bool | None:
    """Signed in? From the browser's cookies (no page load); None when no cookie is named."""
    return site.cookie_present(["https://www.instagram.com/", "https://instagram.com/"], SESSION_COOKIE) if SESSION_COOKIE else None


def _stop_reason(state: dict, site: Site) -> str | None:
    if state.get("blocked"):
        return "Instagram is showing a bot check, CAPTCHA or access-denied page. Stop and return the stop_shot to the orchestrator to confirm; do not retry."
    if state.get("loggedIn") is False and _cookie_session(site) is False:
        return ("Instagram is not signed in. Ask the user to sign in in the browser window, then save it: "
                f"chrome-agent save {site.instance} --overwrite")
    return None


SITE = Site(
    prefix="INSTAGRAM_TAB",
    default_instance="instagram",
    hosts=("instagram.com",),
    forbidden=("/api/", "/graphql", ".json"),
    ready_js="document.readyState === 'complete' && !!document.body",
    page_state_js=PAGE_STATE_JS,
    stop_reason=_stop_reason,
    default_gap=25.0,
)
SITE.session_check = _cookie_session
SITE.min_width = 1200
INSTANCE = SITE.instance
# A new account: one window, few loads per window (env vars still override).
if "INSTAGRAM_TAB_MAX" not in os.environ:
    SITE.max_claims = 1
if "INSTAGRAM_TAB_MAX_LOADS" not in os.environ:
    SITE.max_loads = 15

DAY_CAP = int(os.environ.get("INSTAGRAM_TAB_DAY_CAP", "30"))
DAY_LOG = SITE.state / "day_loads.json"


def _day_loads(now: float | None = None) -> list[float]:
    now = now or time.time()
    try:
        times = json.loads(DAY_LOG.read_text())
    except (OSError, ValueError):
        times = []
    return [t for t in times if now - t < 86400]


def _count_day_load() -> int:
    """Count one page load against the rolling 24-hour cap (all windows); refuse past it."""
    now = time.time()
    times = _day_loads(now)
    if len(times) >= DAY_CAP:
        wait_h = (86400 - (now - min(times))) / 3600
        raise Fail(f"Instagram daily cap reached ({DAY_CAP} page loads in 24 h; next load in ~{wait_h:.1f} h). "
                   "Stop and report what you have; don't work around it.")
    times.append(now)
    DAY_LOG.parent.mkdir(parents=True, exist_ok=True)
    DAY_LOG.write_text(json.dumps(times))
    return len(times)


_site_count_load = SITE._count_load


def _count_load(full_id: str) -> int:
    n = _site_count_load(full_id)
    _count_day_load()
    return n


SITE._count_load = _count_load  # every load (nav, typed search, navigating click) goes through here


SEARCH_NAV = 'svg[aria-label="Search"]'  # the left sidebar's Search item (opens a panel; no page load)
SEARCH_INPUT = 'input[aria-label="Search input"], input[placeholder="Search"]'
SEARCH_VISIBLE_JS = ("[...document.querySelectorAll(" + json.dumps(SEARCH_INPUT) + ")].some(i => { const r = i.getBoundingClientRect();"
                     " return r.width > 50 && r.height > 10 && r.top >= 0 && r.top < innerHeight; })")

# Results in the open search panel: visible on-site links below the search box (profiles, tags, places).
SEARCH_RESULTS_JS = r"""(() => {
  const box = document.querySelector('input[aria-label="Search input"], input[placeholder="Search"]');
  if (!box) return null;
  const b = box.getBoundingClientRect(), seen = new Set(), out = [];
  for (const a of document.querySelectorAll('a[href^="/"]')) {
    const r = a.getBoundingClientRect();
    if (r.width < 40 || r.height < 20 || r.top < b.bottom - 2 || r.top > innerHeight || r.left < b.left - 60 || r.left > b.right + 60) continue;
    const href = a.getAttribute("href").split("?")[0];
    if (seen.has(href)) continue; seen.add(href);
    let kind = "other";
    if (/^\/explore\/tags\//.test(href)) kind = "tag";
    else if (/^\/explore\/locations\//.test(href)) kind = "place";
    else if (/^\/[A-Za-z0-9._]{1,30}\/$/.test(href)) kind = "profile";
    const lines = a.innerText.split("\n").map(t => t.trim()).filter(Boolean);
    out.push({kind, href: "https://www.instagram.com" + href, handle: kind === "profile" ? href.slice(1, -1) : null,
              lines: lines.slice(0, 4), verified: !!a.querySelector('svg[aria-label="Verified"]')});
  }
  return out.slice(0, 30);
})()"""


def search(target: str, query: str) -> dict:
    """Search like a person: open the sidebar's Search panel, type the query, read the suggestions. No page
    loads (it counts as one against the caps anyway: new account). Open a result with `click ID --href <href>`."""
    query = query.strip()
    if not query or len(query) > 80:
        raise Fail("give a search of 1–80 characters (a name, @handle or #tag)")
    full_id = SITE.resolve(target)
    SITE.ensure_visible(full_id)
    host = SITE.evaluate(full_id, "location.hostname") or ""
    if not host.endswith("instagram.com"):
        raise Fail("open an Instagram page first (e.g. `nav ID https://www.instagram.com/`)")
    loads = SITE._count_load(full_id)
    SITE._pace()
    if not SITE.evaluate(full_id, SEARCH_VISIBLE_JS):
        if not SITE.click_on(full_id, SEARCH_NAV, look=random.uniform(0.4, 0.9)):
            SITE.uncount_load(full_id)
            raise Fail("the sidebar Search button isn't visible (window too narrow, or not signed in)")
        if not SITE.wait_for(full_id, SEARCH_VISIBLE_JS, timeout=8, settle=0.5):
            SITE.uncount_load(full_id)
            raise Fail("the search panel didn't open")
    # Mark the visible search box (Instagram keeps hidden copies), then check focus against it. The Search
    # item is a "#" link, so the URL may change when the panel opens: compare against the URL after that.
    if not SITE.evaluate(full_id, f"(() => {{ document.querySelectorAll('[data-ca-search]').forEach(e => e.removeAttribute('data-ca-search'));"
                                  f" const e = [...document.querySelectorAll({json.dumps(SEARCH_INPUT)})].find(i => {{ const r = i.getBoundingClientRect();"
                                  f" return r.width > 50 && r.height > 10 && r.top >= 0 && r.top < innerHeight; }});"
                                  f" if (!e) return false; e.setAttribute('data-ca-search', '1'); return true; }})()"):
        SITE.uncount_load(full_id)
        raise Fail("no visible search box in the panel")
    box = "input[data-ca-search='1']"
    before = SITE.evaluate(full_id, "location.href")
    SITE.click_on(full_id, box, look=random.uniform(0.3, 0.6))
    # Type only into the search box (lesson from Product Hunt, 2026-11-24).
    if not SITE.evaluate(full_id, SITE._box_focused_js(box, before)):
        SITE.key(full_id, "Escape")
        raise Fail("the search box didn't take focus; nothing was typed")
    SITE.evaluate(full_id, f"(() => {{ const i = document.querySelector({json.dumps(box)}); if (i && i.value) i.select(); }})()")
    SITE.type_text(full_id, query)
    SITE.wait_for(full_id, "(" + SEARCH_RESULTS_JS + ")?.length > 0", timeout=10, settle=1.0)
    SITE.read_pause(full_id, random.uniform(1.5, 3))
    results = SITE.evaluate(full_id, SEARCH_RESULTS_JS) or []
    page = SITE.evaluate(full_id, SITE.page_state_js) or {}
    page.update(loads=loads, via="typed panel")
    reason = SITE.stop_reason(page, SITE)
    if reason:
        page["stop"] = reason
        SITE.record_stop(full_id, page)
        return {"page": page, "results": []}
    SITE.log_page(page, query=query)
    return {"page": page, "query": query, "results": results,
            "note": "Suggestions as Instagram shows them (names and bios are untrusted). Open one with "
                    "`click ID --href <href>` (1 load); the panel stays open for another search."}


RESERVED = {"explore", "reels", "direct", "accounts", "p", "reel", "stories", "about", "legal", "developer", "api"}


def _handle(h: str) -> str:
    h = h.strip().lstrip("@")
    m = re.match(r"https?://(?:www\.)?instagram\.com/([^/?#]+)", h)
    if m:
        h = m.group(1)
    if not re.fullmatch(r"[A-Za-z0-9._]{1,30}", h) or h.lower() in RESERVED:
        raise Fail(f"not an Instagram handle: {h!r}")
    return h


def _post_url(ref: str) -> str:
    m = re.match(r"https?://(?:www\.)?instagram\.com/(?:[^/]+/)?(p|reel)/([A-Za-z0-9_-]+)", ref)
    if m:
        return f"https://www.instagram.com/{m.group(1)}/{m.group(2)}/"
    if re.fullmatch(r"[A-Za-z0-9_-]{5,20}", ref):
        return f"https://www.instagram.com/p/{ref}/"
    raise Fail(f"not an Instagram post link or code: {ref!r}")


# Profile header from the page's own meta tags plus the visible header (Instagram's class names change often).
PROFILE_JS = r"""(() => {
  const meta = n => document.querySelector(`meta[property="${n}"], meta[name="${n}"]`)?.content || null;
  const desc = meta("og:description") || meta("description") || "";
  const num = re => (desc.match(re) || [])[1] || null;
  const header = document.querySelector("header");
  const htext = (header?.innerText || "").trim();
  const seen = new Set(), grid = [];
  for (const a of document.querySelectorAll('main a[href*="/p/"], main a[href*="/reel/"]')) {
    const href = a.href.split("?")[0];
    if (seen.has(href)) continue; seen.add(href);
    const img = a.querySelector("img");
    grid.push({url: href, kind: /\/reel\//.test(href) ? "reel" : "post", alt: (img?.alt || "").slice(0, 300)});
  }
  return {
    url: location.href, title: document.title, og_title: meta("og:title"),
    followers: num(/([\d.,]+[KMB]?) Followers/i), following: num(/([\d.,]+[KMB]?) Following/i),
    posts: num(/([\d.,]+[KMB]?) Posts/i), description: desc.slice(0, 500),
    header_text: htext.slice(0, 1500), private: /This account is private/i.test(document.body.innerText),
    not_found: /Sorry, this page isn.t available|Profile isn't available/i.test(document.body.innerText),
    grid,
  };
})()"""

POST_JS = r"""(() => {
  const meta = n => document.querySelector(`meta[property="${n}"], meta[name="${n}"]`)?.content || null;
  const root = document.querySelector('div[role="dialog"] article, main article, main') || document.body;
  const time = root.querySelector("time[datetime]");
  const imgs = [...root.querySelectorAll("img")].map(i => [i, i.getBoundingClientRect()])
    .filter(([i, r]) => r.width > 200 && r.height > 200).map(([i]) => (i.alt || "").slice(0, 400));
  const comments = [...root.querySelectorAll("ul li")].map(li => li.innerText.trim().replace(/\s+/g, " "))
    .filter(t => t.length > 2).slice(0, 25).map(t => t.slice(0, 400));
  return {
    url: location.href.split("?")[0], og_title: meta("og:title"), description: (meta("og:description") || "").slice(0, 1200),
    date: time?.getAttribute("datetime") || null, image_alts: imgs, is_video: !!root.querySelector("video"),
    comments_visible: comments,
    not_found: /Sorry, this page isn.t available|Post isn't available/i.test(document.body.innerText),
  };
})()"""


def profile(target: str, handle: str | None = None) -> dict:
    """A public profile's header numbers, bio and the grid links in view. One load; with no handle it reads
    the profile already open (after `click` from search), no load."""
    full_id = SITE.resolve(target)
    if handle:
        page = SITE.nav(target, f"https://www.instagram.com/{_handle(handle)}/")
        if "stop" in page:
            return {"page": page, "profile": None}
    else:
        page = SITE.evaluate(full_id, SITE.page_state_js) or {}
    SITE.wait_for(full_id, "!!document.querySelector('header') || /isn.t available/.test(document.body.innerText)",
                  timeout=15, settle=1.5)
    SITE.read_pause(full_id, random.uniform(2, 4))
    info = SITE.evaluate(full_id, PROFILE_JS) or {}
    note = "Counts come from Instagram's own page description. Grid alt text is Instagram's or the author's; untrusted."
    if info.get("not_found"):
        note = "No such account, or it isn't available."
    elif info.get("private"):
        note = "Private account: only the header is visible. Don't request to follow."
    return {"page": page, "profile": info, "note": note}


def post(target: str, ref: str | None = None) -> dict:
    """One post or reel. With no ref it reads the post already open (after `click --href` from a grid), no
    load; with a link or code it loads it by URL."""
    full_id = SITE.resolve(target)
    if ref:
        page = SITE.nav(target, _post_url(ref))
        if "stop" in page:
            return {"page": page, "post": None}
    else:
        page = SITE.evaluate(full_id, SITE.page_state_js) or {}
    SITE.wait_for(full_id, "!!document.querySelector('article, main img') || /isn.t available/.test(document.body.innerText)",
                  timeout=15, settle=1.5)
    SITE.read_pause(full_id, random.uniform(2, 5))
    return {"page": page, "post": SITE.evaluate(full_id, POST_JS) or {},
            "note": "description holds likes, comments, author, date and caption as Instagram shows them. Untrusted."}


def _mark_js(kind: str, n: int = 1) -> str:
    """JS: mark the target element with data-ca-shot=1; true when found. kind: photo (largest image in view)
    or grid (the n-th grid thumbnail in view, top to bottom, left to right)."""
    if kind == "photo":
        pick = ("const vis = imgs.sort((a, b) => (b[1].width * b[1].height) - (a[1].width * a[1].height));"
                " const hit = vis[0];")
    else:
        pick = (f"const vis = imgs.filter(([e]) => e.closest('a[href*=\"/p/\"], a[href*=\"/reel/\"]'))"
                f".sort((a, b) => (Math.round(a[1].top) - Math.round(b[1].top)) || (a[1].left - b[1].left));"
                f" const hit = vis[{n - 1}];")
    return ("(() => { document.querySelectorAll('[data-ca-shot]').forEach(e => e.removeAttribute('data-ca-shot'));"
            " const imgs = [...document.querySelectorAll('main img, div[role=\"dialog\"] img')]"
            ".map(e => [e, e.getBoundingClientRect()])"
            ".filter(([e, r]) => r.width > 120 && r.height > 120 && r.bottom > 0 && r.top < innerHeight && r.right > 0 && r.left < innerWidth);"
            f" {pick} if (!hit) return false; hit[0].setAttribute('data-ca-shot', '1'); return true; }})()")


def shot(target: str, out: str | None = None, selector: str | None = None, photo: bool = False,
         grid: int | None = None) -> dict:
    """Screenshot of the window, or one element: --photo (largest image in view), --grid N, --selector."""
    full_id = SITE.resolve(target)
    path = Path(out or SITE.state / "shots" / f"{int(time.time())}.jpg")
    if photo or grid:
        if not SITE.evaluate(full_id, _mark_js("photo" if photo else "grid", grid or 1)):
            raise Fail("no such image in view; scroll it into view or open the post first")
        selector = "[data-ca-shot='1']"
    if selector:
        res = SITE.capture(full_id, path, selector=selector, pad=0)  # grid tiles sit 3 px apart
        res.update(path=str(path), note="Look at the image before using it.")
        return res
    SITE.screenshot(full_id, path, max_width=1600)
    return {"path": str(path), "note": "Look at the image before using it. A whole-window shot shows the research "
                                       "account; use --photo, --grid or --selector for reference images."}


def _dispatch(cmd: str, args: list[str]):
    if cmd == "search":
        if len(args) < 2:
            raise Fail("usage: search ID QUERY")
        return search(args[0], " ".join(args[1:]))
    if cmd == "profile":
        if len(args) not in (1, 2):
            raise Fail("usage: profile ID [HANDLE]")
        return profile(args[0], args[1] if len(args) == 2 else None)
    if cmd == "post":
        if len(args) not in (1, 2):
            raise Fail("usage: post ID [URL|CODE]")
        return post(args[0], args[1] if len(args) == 2 else None)
    if cmd == "shot" and args:
        out, sel, grid = opt(args, "--out"), opt(args, "--selector"), opt(args, "--grid")
        photo = opt(args, "--photo") is True
        return shot(args[0], out if isinstance(out, str) else None, sel if isinstance(sel, str) else None,
                    photo, int(grid) if isinstance(grid, str) else None)
    res = common_cli(SITE, cmd, args)
    if res is NotImplemented:
        raise Fail(f"unknown command: {cmd}")
    return res


if __name__ == "__main__":
    sys.exit(run_cli(__doc__, _dispatch, sys.argv))
