#!/usr/bin/env python3
"""Polite, read-only Newegg research in a shared, signed-in chrome-agent browser (newegg).

Generated by add-research-site/scripts/onboard_site.py scaffold; fill in the readers for the pages
this site's research needs (search results, product pages, reviews, Q&A) and keep them read-only.

CLI (each command prints JSON):

    newegg_tab.py open [--wait [SECONDS]]      claim a window -> {"target": ID} (`stop` when signed out)
    newegg_tab.py search ID QUERY             typed into the search box on newegg.com, else by URL (1 load); cards
                       with item, title, brand, price, was_price, rating, reviews, refurbished, ships_from,
                       direct_from (marketplace), promo
    newegg_tab.py product ID URL              title, brand, model, price, sold_by, ships_from, bullets, specs,
                       rating, ratings_count, histogram, best-seller rank, Q&A count, first reviews (1 load)
    newegg_tab.py reviews ID URL [--sort helpful|newest|highest|lowest|ownership] [--filter current-item|verified|
                       mfr|media|no-incentive ...] [--pages N]   25 a page via the Reviews tab
    newegg_tab.py qa ID URL [--max N]          Q&A tab; AI-assistant answers and store prompts flagged
    newegg_tab.py nav ID URL                   paced page load on newegg.com
    newegg_tab.py shot ID [--out PATH]         screenshot of the window
    newegg_tab.py eval ID JS                   read something off the page
    newegg_tab.py close ID | list | gc         release window / show / clean up claims

Environment (NEWEGG_TAB_*): INSTANCE (newegg), MAX (3 windows), GAP (5 s between loads),
MAX_LOADS (40), STATE (/tmp/chrome-agent-newegg).
"""
import json
import os
import random
import re
import sys
import time
from pathlib import Path
from urllib.parse import quote_plus

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "lib"))
from research_core import Fail, Site, common_cli, opt, pause, run_cli, timed  # noqa: E402

# Where the tab is, whether the site shows the signed-in account, and whether a wall is up.
# TODO: replace the signed-in selectors with the site's own account menu / sign-in link.
PAGE_STATE_JS = r"""(() => {
  const text = ((document.title || "") + " " + (document.body?.innerText || "").slice(0, 4000)).toLowerCase();
  const visible = el => { const r = el.getBoundingClientRect(), s = getComputedStyle(el);
    return r.width > 60 && r.height > 60 && s.visibility !== "hidden" && s.display !== "none"; };
  const challenge = [...document.querySelectorAll("iframe")].some(f =>
    /recaptcha\/.*\/bframe|hcaptcha|challenges\.cloudflare|captcha-delivery|arkoselabs/.test(f.src || "") && visible(f));
  const signedOut = /\bsign in\b|\blog in\b/.test((document.querySelector("header")?.innerText || "").toLowerCase());
  return {url: location.href, title: document.title, loggedIn: signedOut ? false : null,
          blocked: challenge || /access denied|unusual traffic|verify you are (a )?human|press (&|and) hold|are you a robot/.test(text)};
})()"""


def _cookie_session(site: Site) -> bool | None:
    """Signed in? From the browser's cookies (no page load). TODO: name the site's session cookie."""
    return None


def _stop_reason(state: dict, site: Site) -> str | None:
    if state.get("blocked"):
        return "Newegg is showing a bot check, CAPTCHA or access-denied page. Stop and ask the user; do not retry."
    if state.get("loggedIn") is False and _cookie_session(site) is False:
        return ("Newegg is not signed in. Ask the user to sign in in the browser window, then save it: "
                f"chrome-agent save {site.instance} --overwrite")
    return None


SITE = Site(
    prefix="NEWEGG_TAB",
    default_instance="newegg",
    hosts=("newegg.com",),
    forbidden=("/api/", "/graphql", ".json"),
    ready_js="document.readyState === 'complete' && !!document.body",
    page_state_js=PAGE_STATE_JS,
    stop_reason=_stop_reason,
    default_gap=5.0,
)
SITE.session_check = _cookie_session
SITE.min_width = 1200
INSTANCE = SITE.instance



def _js(name: str) -> str:
    return (HERE / "js" / name).read_text()


_SEARCH_BOX = "input[type=search][placeholder^='Search']"


def search(target: str, query: str) -> dict:
    """Search like a person: typed into the search box on a newegg.com page, else by URL. One page load."""
    full_id = SITE.resolve(target)
    SITE.ensure_visible(full_id)
    here = SITE.evaluate(full_id, "location.hostname") or ""
    box = here.endswith("newegg.com") and SITE.evaluate(full_id, f"!!document.querySelector({json.dumps(_SEARCH_BOX)})")
    if box:
        loads = SITE._count_load(full_id)
        with timed("pace_wait"):
            SITE._pace()
        before = SITE.evaluate(full_id, "location.href")
        if not SITE.click_on(full_id, _SEARCH_BOX, look=0.5):
            raise Fail("the search box isn't visible")
        pause(0.4)
        SITE.evaluate(full_id, f"(() => {{ const i = document.querySelector({json.dumps(_SEARCH_BOX)}); if (i && i.value) i.select(); }})()")
        SITE.type_text(full_id, query)
        pause(0.6)
        SITE.key(full_id, "Enter")
        with timed("page_load"):
            SITE.wait_for(full_id, f"location.href !== {json.dumps(before)} && document.readyState === 'complete'",
                          timeout=25, settle=SITE.settle)
        page = SITE.evaluate(full_id, PAGE_STATE_JS) or {}
        page.update(loads=loads, via="typed")
        if _stop_reason(page, SITE):
            page["stop"] = _stop_reason(page, SITE)
    else:
        page = SITE.nav(target, f"https://www.newegg.com/p/pl?d={quote_plus(query)}")
        page["via"] = "url"
    if "stop" in page:
        return {"page": page, "results": []}
    SITE.wait_for(full_id, "document.querySelectorAll('div.goods-container .goods-price').length > 0", timeout=8)
    SITE.read_pause(full_id, random.uniform(2, 3.5))
    results = SITE.evaluate(full_id, _js("search_results.js")) or []
    return {"page": page, "results": results, "count": len(results),
            "note": ("`ships_from` outside the US and `direct_from` mean a marketplace seller, not Newegg: check "
                     "`sold_by` on the product page.")}


def _open_tab(full_id: str, label: str) -> bool:
    """Click a product page tab ("Specs", "Reviews (65)", "Q & A (2)") like a reader."""
    ok = SITE.evaluate(full_id, f"""(() => {{ document.querySelectorAll('[data-ne-tab]').forEach(e => e.removeAttribute('data-ne-tab'));
      const t = [...document.querySelectorAll('.tab-nav')].find(e => new RegExp({json.dumps(label)}).test(e.innerText.trim())
        && e.getBoundingClientRect().width > 0); if (!t) return false; t.setAttribute('data-ne-tab', '1'); return true; }})()""")
    if not ok:
        return False
    if not SITE.click_on(full_id, "[data-ne-tab='1']", look=random.uniform(0.4, 1.0)):
        return False
    pause(random.uniform(1.8, 2.8))
    return True


def _item_of(url: str) -> str:
    m = re.search(r"/p/(?!pl\b)([\w-]+)", url or "")
    if not m:
        raise Fail(f"not a Newegg product URL: {url!r} (expected https://www.newegg.com/<name>/p/<item>)")
    return m.group(1)


def _load_product(target: str, url: str) -> tuple[str, dict]:
    """Open the product (click it in the current results when listed there, else load the URL)."""
    full_id = SITE.resolve(target)
    SITE.ensure_visible(full_id)
    item = _item_of(url)
    here = SITE.evaluate(full_id, "location.href") or ""
    if f"/p/{item}" in here:
        return full_id, {"url": here, "opened": "already open", "loads": None}
    sel = f'div.goods-container a.goods-title[href*="/p/{item}"]'
    if SITE.evaluate(full_id, f"!!document.querySelector({json.dumps(sel)})"):
        loads = SITE._count_load(full_id)
        with timed("pace_wait"):
            SITE._pace()
        if SITE.click_on(full_id, sel, look=random.uniform(0.5, 1.2)) and SITE.wait_for(
                full_id, f"location.pathname.includes('/p/{item}') && document.readyState === 'complete'",
                timeout=20, settle=SITE.settle):
            page = SITE.evaluate(full_id, PAGE_STATE_JS) or {}
            page.update(loads=loads, opened="clicked")
            return full_id, page
        SITE.uncount_load(full_id)
    page = SITE.nav(target, url.split("#")[0])
    page["opened"] = "url"
    return full_id, page


def product(target: str, url: str) -> dict:
    """A product page: title, brand, model, price, seller, bullets, specs, rating summary and histogram,
    best-seller rank, Q&A count. One page load (a click from the current results when listed there)."""
    full_id, page = _load_product(target, url)
    if page.get("stop"):
        return {"page": page, "product": None}
    SITE.read_pause(full_id, random.uniform(2, 3.5))
    tabs = [t for t in ("^Specs", "^Reviews") if _open_tab(full_id, t)]
    data = SITE.evaluate(full_id, _js("product.js")) or {}
    rv = SITE.evaluate(full_id, _js("reviews.js")) or {}
    data["first_reviews"] = rv.get("reviews", [])[:10]
    data["review_flags"] = _review_flags(rv.get("reviews", []))
    SITE.scroll_to_top(full_id)
    return {"page": page, "product": data, "tabs_opened": tabs,
            "note": ("Reviews are pooled across variants (`related_product`). `sold_by` other than Newegg is a "
                     "marketplace seller. Use `reviews` for filters and sorting, `qa` for questions.")}


def _review_flags(revs: list[dict]) -> dict:
    return {"read": len(revs), "verified_owner": sum(1 for r in revs if r.get("verified_owner")),
            "other_variant": sum(1 for r in revs if r.get("related_product")),
            "incentivized": sum(1 for r in revs if r.get("incentivized")),
            "manufacturer_responses": sum(1 for r in revs if r.get("manufacturer_response"))}


FILTERS = {"current-item": "Only see the reviews for the current item", "verified": "Verified Owners",
           "mfr": "Mfr. Responses", "media": "Reviews with Image / Video", "no-incentive": "Non-incentivized Reviews Only"}
SORTS = {"helpful": "Most Helpful", "newest": "Date Posted", "highest": "Highest Rated", "lowest": "Lowest Rated",
         "ownership": "Ownership"}

_SET_SORT_JS = """((label) => { const pane = [...document.querySelectorAll('.tab-pane')].find(e => /customer ratings/.test(e.innerText || ''));
  const s = pane && pane.querySelector('select'); if (!s) return null;
  const o = [...s.options].find(o => o.text.trim() === label); if (!o) return null; if (s.value === o.value) return label;
  Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(s, o.value);
  s.dispatchEvent(new Event('change', {bubbles: true})); return label; })(%s)"""

_MARK_LABEL_JS = """((text) => { document.querySelectorAll('[data-ne-f]').forEach(e => e.removeAttribute('data-ne-f'));
  const l = [...document.querySelectorAll('label.form-checkbox')].find(e => e.innerText.trim().startsWith(text) && e.getBoundingClientRect().width > 0);
  if (!l) return null; l.setAttribute('data-ne-f', '1'); return !!l.querySelector('input')?.checked; })(%s)"""

# The ratings summary for the current filters ("5 out of 5 eggs", "1 customer rating", star percentages).
_SUMMARY_JS = r"""(() => { const p = [...document.querySelectorAll('.tab-pane')].find(e => /out of 5 eggs/.test(e.innerText || ''));
  const t = p ? p.innerText : '';
  const pct = (t.match(/customer ratings?(?:, [\d,]+ with reviews)?\s*\n+([\s\S]*?)\n\s*(?:Customer Images|Do you own)/) || [])[1] || '';
  const hist = {}; pct.split(/\n+/).map(x => x.trim()).filter(x => /^\d+%$/.test(x)).forEach((v, i) => { hist[String(5 - i)] = v; });
  return {rating: parseFloat((t.match(/([\d.]+) out of 5 eggs/) || [])[1]) || null,
          ratings: parseInt(((t.match(/([\d,]+) customer ratings?/) || [])[1] || '').replace(/,/g, '')) || 0,
          with_text: parseInt(((t.match(/([\d,]+) with reviews/) || [])[1] || '').replace(/,/g, '')) || null,
          histogram: hist, no_match: /no reviews matching the selection/i.test(t)}; })()"""

_MARK_NEXT_JS = """(() => { document.querySelectorAll('[data-ne-next]').forEach(e => e.removeAttribute('data-ne-next'));
  const pane = [...document.querySelectorAll('.tab-pane')].find(e => /customer ratings/.test(e.innerText || ''));
  const b = pane && [...pane.querySelectorAll('button, a')].find(e => /^next$/i.test((e.getAttribute('aria-label') || e.title || e.innerText || '').trim())
    && !e.disabled && e.getBoundingClientRect().width > 0);
  if (!b) return false; b.setAttribute('data-ne-next', '1'); return true; })()"""


def reviews(target: str, url: str, sort: str | None = None, filters: list[str] | None = None, pages: int = 1) -> dict:
    """The Reviews tab (25 a page): the page's own sort menu and filter boxes (current item only, verified
    owners, manufacturer responses, with media, non-incentivized only), then `pages` pages via its Next button.
    One page load (none when the product is already open)."""
    if sort and sort not in SORTS:
        raise Fail(f"sort must be one of {', '.join(SORTS)}")
    bad = [f for f in filters or [] if f not in FILTERS]
    if bad:
        raise Fail(f"unknown filter {bad}; use {', '.join(FILTERS)}")
    full_id, page = _load_product(target, url)
    if page.get("stop"):
        return {"page": page, "reviews": []}
    if not _open_tab(full_id, "^Reviews"):
        return {"page": page, "reviews": [], "note": "no Reviews tab on this page"}
    for key, label in FILTERS.items():  # each box to the requested state (a click toggles it)
        checked = SITE.evaluate(full_id, _MARK_LABEL_JS % json.dumps(label))
        if checked is not None and bool(checked) != (key in (filters or [])):
            if SITE.click_on(full_id, "[data-ne-f='1']", look=0.5):
                pause(random.uniform(2, 3))
    if sort:
        SITE.evaluate(full_id, _SET_SORT_JS % json.dumps(SORTS[sort]))
        pause(3)
    out, shown = [], []
    for i in range(max(1, pages)):
        rv = SITE.evaluate(full_id, _js("reviews.js")) or {}
        out += rv.get("reviews", [])
        shown.append(rv.get("showing"))
        if i + 1 < pages:
            if not (SITE.evaluate(full_id, _MARK_NEXT_JS) and SITE.click_on(full_id, "[data-ne-next='1']", look=0.6)):
                break
            pause(random.uniform(2.5, 3.5))
    summary = SITE.evaluate(full_id, _SUMMARY_JS) or {}
    res = {"page": page, "showing": shown, "sort": sort, "filters": filters or [], "summary": summary, "reviews": out,
           "flags": _review_flags(out),
            "note": ("`related_product` reviews are for a sibling (another edition or memory size) pooled into this "
                     "rating: --filter current-item gives this exact item's rating.")}
    if not out and summary.get("no_match"):
        res["note"] = ("No reviews match these filters (the summary is for the filtered set). With current-item, "
                       "the product's headline rating comes from its sibling variants.")
    return res


_ANSWER_MORE_JS = """(() => { let n = 0; document.querySelectorAll('[data-ne-more]').forEach(e => e.removeAttribute('data-ne-more'));
  for (const b of document.querySelectorAll('.tt-c-question__answers button, .tt-c-questions button')) {
    if (/^(\\d+ (more )?answers?|show (more|all) answers?|view \\d+ answers?)$/i.test(b.innerText.trim()) && b.getBoundingClientRect().width > 0) {
      b.setAttribute('data-ne-more', String(n++)); } }
  return n; })()"""


def qa(target: str, url: str, max_open: int = 10) -> dict:
    """The Q & A tab: questions with their answers (more answers opened like a reader, up to `max_open`). AI
    answers ("Newegg AI Assistant") and store-asked prompts are flagged. One page load (none when open)."""
    full_id, page = _load_product(target, url)
    if page.get("stop"):
        return {"page": page, "questions": []}
    if not _open_tab(full_id, "^Q ?& ?A"):
        return {"page": page, "questions": [], "note": "no Q & A tab on this page"}
    n = SITE.evaluate(full_id, _ANSWER_MORE_JS) or 0
    for i in range(min(n, max_open)):
        if SITE.click_on(full_id, f"[data-ne-more='{i}']", look=random.uniform(0.4, 0.9)):
            pause(random.uniform(1.0, 1.8))
    data = SITE.evaluate(full_id, _js("qa.js")) or {}
    qs = data.get("questions", [])
    return {"page": page, "total": data.get("total"), "questions": qs,
            "ai_answers": sum(1 for q in qs for a in q["answers"] if a["ai"]),
            "note": ("`ai` answers are Newegg's AI assistant (generated from the listing, not an owner). Questions "
                     "asked by the store (`asker_badge`: Store, e.g. “Why did you choose this?”) collect owners' "
                     "reasons for buying, not answers.")}

def shot(target: str, out: str | None = None) -> dict:
    full_id = SITE.resolve(target)
    path = Path(out or SITE.state / "shots" / f"{int(time.time())}.jpg")
    SITE.screenshot(full_id, path, max_width=1600)
    return {"path": str(path), "note": "Look at the image before using it."}


def _dispatch(cmd: str, args: list[str]):
    if cmd == "search":
        if len(args) < 2:
            raise Fail("usage: search ID QUERY")
        return search(args[0], " ".join(args[1:]))
    if cmd == "product" and len(args) == 2:
        return product(*args)
    if cmd == "reviews":
        sort, pages = opt(args, "--sort"), int(opt(args, "--pages", 1))
        filters = []
        while "--filter" in args:
            v = opt(args, "--filter")
            if isinstance(v, str):
                filters.append(v)
        if len(args) != 2:
            raise Fail("usage: reviews ID PRODUCT_URL [--sort helpful|newest|highest|lowest|ownership] "
                       "[--filter current-item|verified|mfr|media|no-incentive ...] [--pages N]")
        return reviews(args[0], args[1], sort if isinstance(sort, str) else None, filters, pages)
    if cmd == "qa":
        mx = int(opt(args, "--max", 10))
        if len(args) != 2:
            raise Fail("usage: qa ID PRODUCT_URL [--max N]")
        return qa(args[0], args[1], mx)
    if cmd == "shot" and args:
        out = opt(args, "--out")
        return shot(args[0], out if isinstance(out, str) else None)
    res = common_cli(SITE, cmd, args)
    if res is NotImplemented:
        raise Fail(f"unknown command: {cmd}")
    return res


if __name__ == "__main__":
    sys.exit(run_cli(__doc__, _dispatch, sys.argv))
