#!/usr/bin/env python3
"""Polite, read-only Home Depot research in a shared, signed-in chrome-agent browser (homedepot-research-01).

Generated by add-research-site/scripts/onboard_site.py scaffold; fill in the readers for the pages
this site's research needs (search results, product pages, reviews, Q&A) and keep them read-only.

CLI (each command prints JSON):

    homedepot_tab.py open [--wait [SECONDS]]      claim a window -> {"target": ID} (`stop` when signed out)
    homedepot_tab.py search ID QUERY             typed into the site's search box when a homedepot.com page is
                       open (`page.via`: typed), else the search URL is loaded (one page load either way).
                       Returns the product cards: id, url, brand, title, price, rating, reviews, sponsored, badges.
                       Home Depot often redirects a search to a category page (`page.url`).
    homedepot_tab.py nav ID URL                   paced page load on homedepot.com
    homedepot_tab.py shot ID [--out PATH]         screenshot of the window
    homedepot_tab.py eval ID JS                   read something off the page
    homedepot_tab.py close ID | list | gc         release window / show / clean up claims

Environment (HOMEDEPOT_TAB_*): INSTANCE (homedepot-research-01), MAX (3 windows), GAP (5 s between loads),
MAX_LOADS (40), STATE (/tmp/chrome-agent-homedepot).
"""
import os
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "lib"))
from urllib.parse import quote  # noqa: E402

from research_core import Fail, Site, common_cli, opt, pause, run_cli, timed  # noqa: E402

# Where the tab is, whether the site shows the signed-in account, and whether a wall is up.
# TODO: replace the signed-in selectors with the site's own account menu / sign-in link.
PAGE_STATE_JS = r"""(() => {
  const text = ((document.title || "") + " " + (document.body?.innerText || "").slice(0, 4000)).toLowerCase();
  const visible = el => { const r = el.getBoundingClientRect(), s = getComputedStyle(el);
    return r.width > 60 && r.height > 60 && s.visibility !== "hidden" && s.display !== "none"; };
  const challenge = [...document.querySelectorAll("iframe")].some(f =>
    /recaptcha\/.*\/bframe|hcaptcha|challenges\.cloudflare|captcha-delivery|arkoselabs/.test(f.src || "") && visible(f));
  const signedOut = /\bsign in\b|\blog in\b/.test((document.querySelector("header")?.innerText || "").toLowerCase());
  return {url: location.href, title: document.title, loggedIn: signedOut ? false : null,
          blocked: challenge || /access denied|unusual traffic|verify you are (a )?human|press (&|and) hold|are you a robot/.test(text)};
})()"""


def _cookie_session(site: Site) -> bool | None:
    """Signed in? From the browser's cookies (no page load). TODO: name the site's session cookie."""
    return None


def _stop_reason(state: dict, site: Site) -> str | None:
    if state.get("blocked"):
        return "Home Depot is showing a bot check, CAPTCHA or access-denied page. Stop and ask the user; do not retry."
    if state.get("loggedIn") is False and _cookie_session(site) is False:
        return ("Home Depot is not signed in. Ask the user to sign in in the browser window, then save it: "
                f"chrome-agent save {site.instance} --overwrite")
    return None


SITE = Site(
    prefix="HOMEDEPOT_TAB",
    default_instance="homedepot-research-01",
    hosts=("homedepot.com",),
    forbidden=("/api/", "/graphql", ".json"),
    ready_js="document.readyState === 'complete' && !!document.body",
    page_state_js=PAGE_STATE_JS,
    stop_reason=_stop_reason,
    default_gap=5.0,
)
SITE.session_check = _cookie_session
SITE.min_width = 1200
INSTANCE = SITE.instance


_SEARCH_BOX = "#typeahead-search-field-input"

# Product cards on a search or category page (data-testid="product-pod", keyed by data-product-id).
_RESULTS_JS = r"""(() => {
  const txt = el => (el?.innerText || "").replace(/​/g, "").replace(/\s+/g, " ").trim();
  const flat = el => (el?.textContent || "").replace(/​/g, "").replace(/\s+/g, " ").trim();
  const out = [];
  for (const pod of document.querySelectorAll("[data-product-id]")) {
    if (!pod.querySelector("[data-testid=product-header]")) continue;
    const a = pod.querySelector("[data-testid=product-header] a") || pod.querySelector("a[href*='/p/']");
    const stars = pod.querySelector("[name=simple-rating], [aria-label$=Stars]")?.getAttribute("aria-label") || "";
    const rl = txt(pod.querySelector("[data-testid=product-pod__ratings-link]"));  // "(4.7 / 4332)"
    const rm = rl.match(/\(\s*([\d.]+)\s*\/\s*([\d,]+)\s*\)/);
    // "Limit 5 per order$59.00$89.00 Save $30.00 (34%)": the current price, then the was-price
    const price = flat(pod.querySelector("[data-testid=price-simple], [data-testid*=price]"));
    const prices = price.match(/\$\s?[\d,]+(?:\.\d{2})?/g) || [];
    out.push({
      id: pod.getAttribute("data-product-id"),
      url: a ? new URL(a.getAttribute("href"), location.origin).href : null,
      brand: txt(pod.querySelector("[data-testid=attribute-brandname-inline]")) || null,
      title: txt(pod.querySelector("[data-testid=attribute-product-label]")) || null,
      price: prices[0] ? prices[0].replace(/\s/g, "") : null,
      was_price: /save/i.test(price) && prices[1] ? prices[1] : null,
      price_text: price.slice(0, 80) || null,
      rating: rm ? parseFloat(rm[1]) : (parseFloat((stars.match(/[\d.]+/) || [])[0]) || null),
      reviews: rm ? parseInt(rm[2].replace(/,/g, "")) : null,
      sponsored: /\bsponsored\b/i.test(txt(pod).slice(0, 300)),
      badges: txt(pod.querySelector("[data-testid=pod-header]")) || null,
    });
  }
  return out;
})()"""


def search(target: str, query: str) -> dict:
    """Search like a person: typed into the search box on a homedepot.com page, else by URL. One page load."""
    full_id = SITE.resolve(target)
    SITE.ensure_visible(full_id)
    here = SITE.evaluate(full_id, "location.hostname") or ""
    box = here.endswith("homedepot.com") and SITE.evaluate(full_id, f"!!document.querySelector({_SEARCH_BOX!r})")
    if box:
        loads = SITE._count_load(full_id)
        with timed("pace_wait"):
            SITE._pace()
        before = SITE.evaluate(full_id, "location.href")
        if not SITE.click_on(full_id, _SEARCH_BOX, look=0.5):
            raise Fail("the search box isn't visible")
        pause(0.4)
        SITE.evaluate(full_id, f"(() => {{ const i = document.querySelector({_SEARCH_BOX!r}); if (i && i.value) i.select(); }})()")
        SITE.type_text(full_id, query)
        pause(0.6)
        SITE.key(full_id, "Enter")
        with timed("page_load"):
            SITE.wait_for(full_id, f"location.href !== {before!r} && document.readyState === 'complete' && "
                                   "!!document.querySelector('[data-product-id], h1')", timeout=25, settle=SITE.settle)
        page = SITE.evaluate(full_id, PAGE_STATE_JS) or {}
        page.update(loads=loads, via="typed")
        reason = _stop_reason(page, SITE)
        if reason:
            page["stop"] = reason
    else:
        page = SITE.nav(target, f"https://www.homedepot.com/s/{quote(query)}")
        page["via"] = "url"
    if "stop" in page:
        return {"page": page, "results": []}
    SITE.wait_for(full_id, "document.querySelectorAll('[data-product-id]').length > 0", timeout=8)
    SITE.read_pause(full_id, 2.5)
    results = SITE.evaluate(full_id, _RESULTS_JS) or []
    return {"page": page, "results": results, "count": len(results),
            "note": "Sponsored cards are ads (`sponsored`). Ratings and review counts are Home Depot's own, "
                    "which include syndicated reviews from the brand's site."}


def shot(target: str, out: str | None = None) -> dict:
    full_id = SITE.resolve(target)
    path = Path(out or SITE.state / "shots" / f"{int(time.time())}.jpg")
    SITE.screenshot(full_id, path, max_width=1600)
    return {"path": str(path), "note": "Look at the image before using it."}


def _dispatch(cmd: str, args: list[str]):
    if cmd == "search":
        if len(args) < 2:
            raise Fail("usage: search ID QUERY")
        return search(args[0], " ".join(args[1:]))
    if cmd == "shot" and args:
        out = opt(args, "--out")
        return shot(args[0], out if isinstance(out, str) else None)
    res = common_cli(SITE, cmd, args)
    if res is NotImplemented:
        raise Fail(f"unknown command: {cmd}")
    return res


if __name__ == "__main__":
    sys.exit(run_cli(__doc__, _dispatch, sys.argv))
